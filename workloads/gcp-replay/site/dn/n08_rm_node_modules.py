"""n08 删除 node_modules（大量小文件 + 符号链接）."""

from __future__ import annotations

import json
import pathlib
import shutil
import sys
import time

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

from common import main_guard  # noqa: E402
import dn_common as dn  # noqa: E402

PKG = {
    "name": "dn-rmnm",
    "version": "1.0.0",
    "private": True,
    "dependencies": {"is-odd": "3.0.1", "left-pad": "1.3.0"},
}


def run(report):
    dn.node_versions(report)
    base = dn.case_dir("n08-rm-node-modules")
    proj = base / "proj"
    proj.mkdir(parents=True, exist_ok=True)
    (proj / "package.json").write_text(json.dumps(PKG, indent=2) + "\n")
    store = dn.STATE / "pnpm-store"
    with report.step("pnpm install"):
        dn.nrun(
            ["pnpm", "install", "--store-dir", str(store), "--reporter", "append-only"],
            cwd=proj,
            timeout=900,
        )
    nm = proj / "node_modules"
    files = dn.nrun(
        ["bash", "-c", "find node_modules | wc -l"], cwd=proj
    ).stdout.strip()
    links = dn.nrun(
        ["bash", "-c", "find node_modules -type l | wc -l"], cwd=proj
    ).stdout.strip()
    dn.record_compat(report, "node_modules_entries", files)
    dn.record_compat(report, "node_modules_symlinks", links)
    report.check(
        int(files) > 20,
        "node_modules 已生成（含符号链接）",
        files=files,
        symlinks=links,
    )

    t0 = time.time()
    with report.step("rm -rf node_modules"):
        dn.nrun(["rm", "-rf", "node_modules"], cwd=proj, timeout=900)
    rm_s = time.time() - t0
    report.data.setdefault("metrics", {})["rm_node_modules_s"] = round(rm_s, 2)
    report.check(not nm.exists(), "node_modules 已删除")
    again = dn.nsh(["rm", "-rf", "node_modules"], cwd=proj, timeout=300)
    report.check(again.returncode == 0, "重复删除无错误", rc=again.returncode)
    report.sync("n08 final")


if __name__ == "__main__":
    main_guard(run, "n08-rm-node-modules")
